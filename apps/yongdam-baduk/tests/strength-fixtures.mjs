/** Exhaustive local ladder reader used only to establish this fixture's trap.
 * A defending chain with >=3 liberties escapes. Defence can extend or capture
 * an adjacent chain in atari. Attack branches on every remaining liberty. */
export function ladderCanBeCaptured(state,target,depth=60){
 if(!state.board[target])return true;
 const color=state.board[target],g=groupAt(state.board,target,state.size);
 if(g.liberties.length>=3||depth<=0)return false;
 const moves=new Set(g.liberties);
 if(state.toPlay===color)for(const p of g.stones){const x=p%state.size,y=Math.floor(p/state.size);for(const q of [x>0?p-1:-1,x<state.size-1?p+1:-1,y>0?p-state.size:-1,y<state.size-1?p+state.size:-1])if(q>=0&&state.board[q]===3-color){const opp=groupAt(state.board,q,state.size);if(opp.liberties.length===1)moves.add(opp.liberties[0])}}
 const results=[];for(const index of moves){const r=play(state,index);if(r.ok)results.push(ladderCanBeCaptured(r.state,target,depth-1))}
 return state.toPlay===color?results.every(Boolean):results.some(Boolean);
}
