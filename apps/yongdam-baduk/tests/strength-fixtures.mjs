/** Hand-authored tactical fixtures. Expected moves are local reading checks,
 * not rank tests or an Elo benchmark. Indexing is top-left, zero-based. */
import {newGame,play,groupAt} from '../dist/engine.js';
export function fromDiagram(name,rows,toPlay=1,extra={}) {
 const lines=rows.trim().split('\n').map(s=>s.trim());
 const size=lines.length;
 if(![9,13,19].includes(size)||lines.some(s=>s.length!==size))throw new Error('Invalid fixture '+name);
 const board=lines.join('').split('').map(c=>c==='X'?1:c==='O'?2:0);
 const s={...newGame(size),board,toPlay,history:[board.join('')],...extra};
 for(let i=0;i<board.length;i++) if(board[i]&&!groupAt(board,i,size).liberties.length)throw new Error('Zero-liberty group in '+name+' at '+i);
 return s;
}
